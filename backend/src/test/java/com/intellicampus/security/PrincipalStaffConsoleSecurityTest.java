    private PasswordEncoder passwordEncoder = new BCryptPasswordEncoder();

    private AdminStaffService adminStaffService;
    private StaffAuthService staffAuthService;
    private UserService userService;

    private Department csDept;
    private User principalUser;

    @BeforeEach
    void setUp() {
        adminStaffService = new AdminStaffService(
                userRepository,
                departmentRepository,
                passwordEncoder,
                auditChainService,
                emailService,
                refreshTokenRepository
        );

        staffAuthService = new StaffAuthService(
                userRepository,
                departmentRepository,
                passwordEncoder,
                jwtTokenProvider,
                passwordResetTokenRepository,
                refreshTokenRepository,
                rateLimitRepository,
                auditChainService,
                emailService
        );

        userService = new UserService(
                userRepository,
                null,
                departmentRepository,
                null,
                new CsvUserValidator(),
                passwordEncoder
        );

        csDept = new Department("CSE", "Computer Science");
        csDept.setId(1L);

        principalUser = new User("PRI-2026-001", Role.PRINCIPAL, "Principal Dr. Patil", "principal@campus.edu", passwordEncoder.encode("Principal#2026"), csDept);
        principalUser.setId(1L);
    }

    @Nested
    @DisplayName("1. Staff Creation & Direct Password Login")
    class StaffCreationAndLoginTests {

        @Test
        @DisplayName("Staff created with name, email, direct password, and role; user code is auto-generated and unique")
        void testStaffCreatedWithDirectPasswordAndAutoGeneratedCode() {
            AdminStaffCreateDto dto = new AdminStaffCreateDto(
                    "Prof. Alan Turing",
                    "turing@campus.edu",
                    "Turing#2026Pass",
                    Role.FACULTY,
                    "Computer Science"
            );

            when(userRepository.existsByEmailIgnoreCase("turing@campus.edu")).thenReturn(false);
            when(departmentRepository.findByName("Computer Science")).thenReturn(Optional.of(csDept));
            when(userRepository.save(any(User.class))).thenAnswer(inv -> {
                User u = inv.getArgument(0);
                u.setId(10L);
                return u;
            });

            AdminStaffResponseDto resp = adminStaffService.createStaff(dto, principalUser);

            assertNotNull(resp);
            assertEquals("Prof. Alan Turing", resp.getName());
            assertEquals("turing@campus.edu", resp.getEmail());
            assertEquals(Role.FACULTY, resp.getRole());
            assertNotNull(resp.getUserCode());
            assertTrue(resp.getUserCode().startsWith("CSE-2026-"));
            assertFalse(resp.getMustChangePassword(), "Direct password setup must not force password change on first login");
            assertNull(resp.getTemporaryPassword());

            // Password was BCrypt-hashed
            verify(userRepository).save(argThat(u ->
                    passwordEncoder.matches("Turing#2026Pass", u.getPasswordHash())
            ));

            // Audit logged without password
            verify(auditChainService).recordEntry(
                    eq(1L),
                    eq("Principal Dr. Patil"),
                    eq("STAFF_CREATED"),
                    eq("USER"),
                    eq("10"),
                    anyString(),
                    contains("turing@campus.edu"),
                    anyString()
            );
        }

        @Test
        @DisplayName("Staff can log in with exactly the email and password entered by the Principal")
        void testStaffCanLoginWithSameEmailAndPassword() {
            String rawPassword = "Strong#Pass2026";
            String hashedPassword = passwordEncoder.encode(rawPassword);

            User staff = new User("CSE-2026-001", Role.FACULTY, "Prof. Ada Lovelace", "ada@campus.edu", hashedPassword, csDept);
            staff.setId(20L);
            staff.setStatus(UserStatus.ACTIVE);
            staff.setMustChangePassword(false);

            when(userRepository.findByEmail("ada@campus.edu")).thenReturn(Optional.of(staff));
            when(jwtTokenProvider.generateAccessToken(eq(staff), isNull())).thenReturn("mock_access_jwt");
            when(userRepository.save(any(User.class))).thenAnswer(inv -> inv.getArgument(0));

            AuthResponseDto loginResp = staffAuthService.loginStaff(new LoginRequestDto("ada@campus.edu", rawPassword));

            assertNotNull(loginResp);
            assertEquals("mock_access_jwt", loginResp.getAccessToken());
            assertNotNull(loginResp.getUser());
            assertEquals("ada@campus.edu", loginResp.getUser().getEmail());
            assertEquals(Role.FACULTY, loginResp.getUser().getRole());
            assertFalse(staff.getMustChangePassword());
        }
    }

    @Nested
    @DisplayName("2. Role Portals & Validation Guards")
    class RoleAndValidationGuardTests {

        @Test
        @DisplayName("Weak password (<8 chars, or missing uppercase/lowercase/digit/special) is rejected")
        void testWeakPasswordRejected() {
            AdminStaffCreateDto weakDto = new AdminStaffCreateDto(
                    "Dr. Weak", "weak@campus.edu", "short", Role.FACULTY, "Computer Science"
            );

            when(userRepository.existsByEmailIgnoreCase("weak@campus.edu")).thenReturn(false);
            when(departmentRepository.findByName("Computer Science")).thenReturn(Optional.of(csDept));

            ResponseStatusException ex = assertThrows(ResponseStatusException.class, () ->
                    adminStaffService.createStaff(weakDto, principalUser));
            assertEquals(HttpStatus.BAD_REQUEST, ex.getStatusCode());
            assertTrue(ex.getReason().contains("Password must be at least 8 characters"));
        }

        @Test
        @DisplayName("Duplicate email (case-insensitive) is rejected with 409 Conflict")
        void testDuplicateEmailRejected() {
            AdminStaffCreateDto dto = new AdminStaffCreateDto(
                    "Dr. Duplicate", "DUP@campus.edu", "Valid#Pass2026", Role.FACULTY, "Computer Science"
            );

            when(userRepository.existsByEmailIgnoreCase("dup@campus.edu")).thenReturn(true);

            ResponseStatusException ex = assertThrows(ResponseStatusException.class, () ->
                    adminStaffService.createStaff(dto, principalUser));
            assertEquals(HttpStatus.CONFLICT, ex.getStatusCode());
            assertTrue(ex.getReason().contains("Email is already registered"));
        }

        @Test
        @DisplayName("Creating STUDENT or PRINCIPAL is rejected with 403 Forbidden on the staff endpoint")
        void testStudentAndPrincipalCreationRejected() {
            AdminStaffCreateDto studentDto = new AdminStaffCreateDto(
                    "Student X", "student@campus.edu", "Valid#Pass2026", Role.STUDENT, "Computer Science"
            );
            ResponseStatusException ex1 = assertThrows(ResponseStatusException.class, () ->
                    adminStaffService.createStaff(studentDto, principalUser));
            assertEquals(HttpStatus.FORBIDDEN, ex1.getStatusCode());

            AdminStaffCreateDto principalDto = new AdminStaffCreateDto(
                    "Principal Y", "prin2@campus.edu", "Valid#Pass2026", Role.PRINCIPAL, "Computer Science"
            );
            ResponseStatusException ex2 = assertThrows(ResponseStatusException.class, () ->
                    adminStaffService.createStaff(principalDto, principalUser));
            assertEquals(HttpStatus.FORBIDDEN, ex2.getStatusCode());
        }
    }

    @Nested
    @DisplayName("3. Principal Student Protection Barrier (View Only)")
    class StudentProtectionBarrierTests {

        private User studentUser;

        @BeforeEach
        void initStudent() {
            studentUser = new User("STU-2026-001", Role.STUDENT, "Rahul Student", "rahul@campus.edu", "hash", csDept);
            studentUser.setId(99L);
        }

        @Test
        @DisplayName("Principal cannot modify student status via AdminStaffService (403 Forbidden)")
        void testPrincipalCannotModifyStudentStatus() {
            when(userRepository.findById(99L)).thenReturn(Optional.of(studentUser));

            ResponseStatusException ex = assertThrows(ResponseStatusException.class, () ->
                    adminStaffService.updateStaffStatus(99L, new AdminStaffStatusDto(UserStatus.DISABLED), principalUser));
            assertEquals(HttpStatus.FORBIDDEN, ex.getStatusCode());
            assertTrue(ex.getReason().contains("Principals cannot modify student accounts"));
        }

        @Test
        @DisplayName("Principal cannot delete student via AdminStaffService (403 Forbidden)")
        void testPrincipalCannotDeleteStudent() {
            when(userRepository.findById(99L)).thenReturn(Optional.of(studentUser));

            ResponseStatusException ex = assertThrows(ResponseStatusException.class, () ->
                    adminStaffService.deleteStaff(99L, principalUser));
            assertEquals(HttpStatus.FORBIDDEN, ex.getStatusCode());
            assertTrue(ex.getReason().contains("Principals cannot modify student accounts"));
        }

        @Test
        @DisplayName("Principal cannot reset student password via AdminStaffService (403 Forbidden)")
        void testPrincipalCannotResetStudentPassword() {
            when(userRepository.findById(99L)).thenReturn(Optional.of(studentUser));

            ResponseStatusException ex = assertThrows(ResponseStatusException.class, () ->
                    adminStaffService.resetStaffPassword(99L, "New#Password2026", principalUser));
            assertEquals(HttpStatus.FORBIDDEN, ex.getStatusCode());
            assertTrue(ex.getReason().contains("Principals cannot modify student accounts"));
        }

        @Test
        @DisplayName("Principal cannot delete student via UserService (403 Forbidden)")
        void testPrincipalCannotDeleteStudentViaUserService() {
            when(userRepository.findById(99L)).thenReturn(Optional.of(studentUser));

            ResponseStatusException ex = assertThrows(ResponseStatusException.class, () ->
                    userService.deleteUser(99L));
            assertEquals(HttpStatus.FORBIDDEN, ex.getStatusCode());
            assertTrue(ex.getReason().contains("student"));
        }

        @Test
        @DisplayName("Principal cannot reset student password via UserService (403 Forbidden)")
        void testPrincipalCannotResetStudentPasswordViaUserService() {
            when(userRepository.findById(99L)).thenReturn(Optional.of(studentUser));

            ResponseStatusException ex = assertThrows(ResponseStatusException.class, () ->
                    userService.resetUserPassword(99L, "New#Password2026"));
            assertEquals(HttpStatus.FORBIDDEN, ex.getStatusCode());
            assertTrue(ex.getReason().contains("student"));
        }
    }

    @Nested
    @DisplayName("4. Staff CSV Ingestion & Account Lockout")
    class CsvAndLockoutTests {

        @Test
        @DisplayName("Bulk CSV accepts valid staff rows and rejects STUDENT rows with clear message")
        void testCsvImportAcceptsStaffAndRejectsStudents() {
            List<String> csvLines = List.of(
                    "full_name,email,password,role,department",
                    "Prof. Charles Babbage,babbage@campus.edu,Babbage#2026Pass,FACULTY,Computer Science",
                    "Rohan Student,rohan@campus.edu,Rohan#2026Pass,STUDENT,Computer Science",
                    "Fake Principal,prin@campus.edu,Prin#2026Pass,PRINCIPAL,Computer Science"
            );

            when(departmentRepository.findByName("Computer Science")).thenReturn(Optional.of(csDept));
            when(userRepository.existsByEmail("babbage@campus.edu")).thenReturn(false);
            when(userRepository.save(any(User.class))).thenAnswer(inv -> {
                User u = inv.getArgument(0);
                ReflectionTestUtils.setField(u, "id", 101L);
                return u;
            });

            CsvImportResultDto result = userService.importCsv(csvLines);

            assertNotNull(result);
            assertEquals(1, result.getImportedCount());
            assertEquals(2, result.getFailedCount());
            assertTrue(result.getErrors().stream().anyMatch(e -> e.contains("Students register themselves on the Student portal")));
            assertTrue(result.getErrors().stream().anyMatch(e -> e.contains("Principal cannot be imported")));
        }

        @Test
        @DisplayName("Generic error on invalid credentials & lockout after 5 consecutive failed logins")
        void testGenericErrorAndAccountLockout() {
            User staff = new User("CSE-2026-002", Role.FACULTY, "Prof. Newton", "newton@campus.edu", passwordEncoder.encode("Newton#2026"), csDept);
            staff.setId(35L);
            staff.setStatus(UserStatus.ACTIVE);
            staff.setFailedAttempts(4); // 5th attempt

            when(userRepository.findByEmail("newton@campus.edu")).thenReturn(Optional.of(staff));

            BadCredentialsException ex = assertThrows(BadCredentialsException.class, () ->
                    staffAuthService.loginStaff(new LoginRequestDto("newton@campus.edu", "WrongPassword!")));

            assertEquals("Invalid email or password", ex.getMessage(), "Must use generic error message to prevent enumeration");
            assertEquals(5, staff.getFailedAttempts());
            assertEquals(UserStatus.LOCKED, staff.getStatus());
            assertNotNull(staff.getLockedUntil());
        }
    }
